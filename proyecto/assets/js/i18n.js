/** Claves cuyo valor contiene HTML y debe insertarse con innerHTML */
const HTML_KEYS = new Set(["hero.badge", "about.eduTitle", "exp.job4Title", "projects.p4Title"]);

let currentLang = localStorage && false ? "es" : "es"; // (localStorage no se usa en Claude artifacts; estado en memoria)

function applyLanguage(lang){
  currentLang = lang;
  const dict = translations[lang];
  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] === undefined) return;
    if (HTML_KEYS.has(key)) {
      el.innerHTML = dict[key];
    } else {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  // Language switch visual state
  const toggle = document.getElementById("langToggle");
  const esLabel = document.getElementById("langEs");
  const enLabel = document.getElementById("langEn");
  if (toggle) {
    toggle.setAttribute("aria-checked", lang === "en" ? "true" : "false");
    toggle.setAttribute("aria-label", lang === "en" ? "Switch language to Spanish" : "Cambiar idioma a inglés");
  }
  if (esLabel && enLabel) {
    esLabel.classList.toggle("active-lang", lang === "es");
    enLabel.classList.toggle("active-lang", lang === "en");
  }

  // Re-render gallery / modal texts that depend on JS data (projects-data.js)
  if (typeof refreshDynamicContent === "function") refreshDynamicContent(lang);
}
